// Два решения про стопку панелей главного окна (.mw-panel-stack в
// MainWindow.tsx): «достижима ли эта панель» и «куда теперь уходит фокус».
// Оба — вопросы БЕЗ DOM: ответ зависит только от роли панели (живая или
// снимок уезжающей) и от фазы цикла применения, а не от того, что сейчас
// лежит в дереве. Поэтому они здесь, чистыми функциями: `node --test`
// гоняет чистые модули (JSX не компилирует, jsdom в зависимостях нет), и
// это единственное место, где на такие решения можно держать регрессию.
//
// Причина у обоих одна и та же — путаница между ЖИВОЙ панелью уровня и
// СНИМКОМ уезжающей, который держится 200мс ради анимации. На ней уже
// ломался перенос фокуса в список (снимок уносил с собой ref, см.
// panel-focus.test.ts), и ровно из неё растут оба дефекта, которые эти
// функции закрывают: снимок оставался интерактивным, а фокус после
// действия из КОРНЯ оставался в <body>.

/** Атрибуты, которыми панель стопки объявляет свою достижимость. */
export type PanelGuard = Record<string, string>

// Снимок уезжающей панели — картинка, а не интерфейс: 200мс он лежит в той
// же ячейке грида поверх новой панели (а при prefers-reduced-motion:
// reduce — просто стоит на ней без движения) и всё это время принимал
// клики по кнопкам уровня, который человек уже покинул. Изымать его надо
// ЦЕЛИКОМ, а не только от мыши: невидимый для мыши, но оставшийся в дереве
// доступности снимок — тот же самый дефект для того, кто слушает читалку,
// и лишний tab-стоп для того, кто ходит по Tab.
//
// inert — ровно это одним атрибутом (мышь, фокус, дерево доступности,
// выделение текста, поиск по странице), и он нативный, без нашей имитации.
// В паре с ним идут aria-hidden и снятый tab-стоп (panelTabStop ниже) плюс
// pointer-events: none в styles.css — это пол для WebKit старше 15.5
// (macOS 12.0…12.3 при минимуме приложения 12.0), где inert ещё не
// поддержан: там все три facets дефекта закрыты средствами, которые
// поддержаны всегда.
//
// Пустая строка, а не true: атрибут булев по HTML, а React 18 сериализовал
// бы inert={false} в inert="false" — присутствие атрибута и есть inert,
// то есть «ложное» значение сделало бы панель inert точно так же.
// Свежий объект на каждый вызов, а не общая константа: функция чистая, и
// общий изменяемый объект в props двух панелей — ровно тот род связи между
// живой панелью и снимком, из которого растут оба дефекта здесь.
export function panelGuard(live: boolean): PanelGuard {
  return live ? {} : { inert: '', 'aria-hidden': 'true' }
}

/**
 * Tab-стоп внутри панели (контейнер списка, поле Ask AI) — только у живой.
 * Тот же флаг `live`, что отдаёт ref'ы живой панели: «реальна» панель или
 * нет — ОДНО условие, а не три независимых.
 */
export function panelTabStop(live: boolean): 0 | -1 {
  return live ? 0 : -1
}

/** Фаза цикла применения (см. apply-state.ts), от которой зависит фокус. */
export type ApplyPhase = 'idle' | 'pending' | 'proposed'

/** Куда переводить DOM-фокус после того, как живая панель сменилась. */
export type FocusTarget = 'none' | 'list' | 'prompt' | 'apply'

/**
 * Идентичность ТОГО, ЧТО СЕЙЧАС СТОИТ на месте уровня меню.
 *
 * Эффект переноса фокуса раньше смотрел на один idlePanelKey — ключ уровня.
 * Этого не хватало ровно в одном, самом частом случае: действие, запущенное
 * из КОРНЯ. Панель Accept/Cancel снимает список со экрана (фокус утекает в
 * <body> без blur — удаление сфокусированного узла не порождает события), а
 * по возврату уровень тот же самый, корень: idlePanelKey не менялся, эффект
 * не перезапускался, и фокус оставался в <body> — ни стрелок, ни Enter, ни
 * цели для Tab, пока человек не щёлкнет мышью. Фаза входит в ключ, поэтому
 * каждая подмена живой панели (idle → pending → proposed → idle) считается
 * сменой, какой она и является.
 */
export function livePanelKey(phase: ApplyPhase, idlePanelKey: string): string {
  return phase === 'idle' ? idlePanelKey : `apply:${phase}`
}

/**
 * Фокус идёт за ЖИВОЙ панелью — и только если он был в меню до подмены
 * (menuHadFocus): человек, который печатает в редакторе и запускает
 * действие хоткеем, фокуса не отдавал и отбирать его у него нечем.
 *
 * Цель для панели применения — сама панель, а не кнопка на ней, и это
 * решение, а не упрощение. Accept затирает текст человека предложением
 * модели, и вернуть прежний можно только через Undo редактора — поэтому у
 * него намеренно тугой хоткей (⇧⌘⏎); фокус на кнопке Accept свёл бы его к
 * голому Enter с другой стороны. Фокус на Cancel тоже не годится: Enter
 * означает «подтвердить» почти везде, и под ним оказалось бы «выбросить
 * предложение». На экране в этот момент два бейджа, ⇧⌘⏎ и ⎋, и обе эти
 * клавиши работают из любого места окна — а фокус на панели не добавляет к
 * ним третьего, необъявленного смысла, но ставит Accept и Cancel следующими
 * же остановками Tab и объявляет панель читалке. Как только цикл закрыт,
 * фокус возвращается в список, где снова работают стрелки и Enter.
 */
export function nextFocusTarget(input: {
  menuHadFocus: boolean
  phase: ApplyPhase
  showingPrompt: boolean
}): FocusTarget {
  if (!input.menuHadFocus) return 'none'
  if (input.phase !== 'idle') return 'apply'
  return input.showingPrompt ? 'prompt' : 'list'
}
