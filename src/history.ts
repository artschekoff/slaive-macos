// Журнал расшифровок: всё, что можно посчитать без DOM и без бэкенда —
// подпись плитки и её дата. Вынесено отдельно от HistoryView.tsx по той же
// причине, что format.ts отдельно от Settings.tsx: обрезка текста и
// форматирование даты проверяются тестом, а не глазами на живой истории,
// которую для проверки пришлось бы сначала надиктовать.
//
// Приватность: сюда приходит личная речь пользователя. Ни одна функция ниже
// ничего не пишет в консоль — это то же правило, что и на стороне Rust.

/** Сколько символов расшифровки помещается на плитку. Плитка — для
 *  УЗНАВАНИЯ, а не для чтения: две строки в сетке из трёх колонок на окне
 *  720px — это примерно столько. Полный текст достаётся по нажатию, он и так
 *  весь лежит в записи. */
export const PREVIEW_LIMIT = 120

/**
 * Начало текста для плитки. Переносы и повторные пробелы схлопываются в один
 * пробел: в документе редактора перенос — обычный символ (см.
 * transcript-editor.ts), и надиктованный абзац с переносами на плитке в две
 * строки выглядел бы дырявым.
 *
 * Обрезаем по границе слова, а не посреди него: половина слова с многоточием
 * читается как опечатка. Если же в тексте нет ни одного пробела в пределах
 * лимита (длинный путь, ссылка, склеенный текст), режем по лимиту — иначе
 * плитка оказалась бы пустой.
 *
 * Текст короче лимита возвращается КАК ЕСТЬ, без многоточия: многоточие
 * означает «дальше есть ещё», и ставить его там, где дальше ничего нет, —
 * враньё в единственном месте, по которому запись узнают.
 */
export function previewText(text: string, limit: number = PREVIEW_LIMIT): string {
  const flat = text.replace(/\s+/g, ' ').trim()
  if (flat.length <= limit) return flat
  const cut = flat.slice(0, limit)
  const lastSpace = cut.lastIndexOf(' ')
  // Половина лимита — порог «слово всё-таки нашлось»: если последний пробел
  // стоит в самом начале, обрезка по нему оставила бы на плитке одно слово
  // вместо двух строк.
  const body = lastSpace > limit / 2 ? cut.slice(0, lastSpace) : cut
  return `${body.trimEnd()}…`
}

const MONTHS = [
  'Jan',
  'Feb',
  'Mar',
  'Apr',
  'May',
  'Jun',
  'Jul',
  'Aug',
  'Sep',
  'Oct',
  'Nov',
  'Dec',
]

const pad2 = (n: number) => String(n).padStart(2, '0')

/**
 * Дата записи в человеческом виде, по-английски, как весь интерфейс.
 *
 * В файле время лежит в UTC (миллисекунды от эпохи), а показывается в
 * МЕСТНОМ времени: «Today, 14:32» про запись, сделанную полчаса назад, — это
 * то, по чему её узнают, а UTC-время для этого бесполезно ровно настолько,
 * насколько часовой пояс пользователя отличается от нуля.
 *
 * «Today»/«Yesterday» считаются по календарным суткам, а не по «меньше 24
 * часов назад»: запись, сделанную вчера в 23:50, человек называет вчерашней и
 * в час ночи, и в девять утра.
 *
 * Собрано вручную, а не через `toLocaleString`: формат тогда зависел бы от
 * системной локали, и на русской системе английский интерфейс показывал бы
 * «3 сент. 2026 г.». Заодно результат становится проверяемым тестом.
 *
 * Время 24-часовое: «14:32» одинаково читается в любой стране, а «2:32 PM» в
 * интерфейсе без единого другого AM/PM выглядело бы случайностью.
 *
 * ponytail: формат зашит, без настройки — менять, если появится запрос на
 * 12-часовое время.
 */
export function formatEntryDate(ms: number, now: Date = new Date()): string {
  const d = new Date(ms)
  if (!Number.isFinite(d.getTime())) return ''
  const time = `${pad2(d.getHours())}:${pad2(d.getMinutes())}`

  const sameDay = (a: Date, b: Date) =>
    a.getFullYear() === b.getFullYear() &&
    a.getMonth() === b.getMonth() &&
    a.getDate() === b.getDate()

  if (sameDay(d, now)) return `Today, ${time}`
  const yesterday = new Date(now.getFullYear(), now.getMonth(), now.getDate() - 1)
  if (sameDay(d, yesterday)) return `Yesterday, ${time}`

  const date = `${MONTHS[d.getMonth()]} ${d.getDate()}`
  // Год — только когда он не текущий: в истории за последние двести записей
  // он почти всегда текущий и только занимает место на плитке.
  if (d.getFullYear() !== now.getFullYear()) return `${date}, ${d.getFullYear()}, ${time}`
  return `${date}, ${time}`
}

/**
 * Длительность записи — «мм:сс», как в любом плеере. Час и больше —
 * «ч:мм:сс»; такой диктовки не бывает, но и врать про неё «73:05» незачем.
 * Отрицательное и нечисловое (битая строка в файле, которую разбор всё же
 * пропустил) показываем как 0:00, а не «NaN:NaN».
 */
export function formatDuration(seconds: number): string {
  if (!Number.isFinite(seconds) || seconds < 0) return '0:00'
  const total = Math.round(seconds)
  const s = total % 60
  const m = Math.floor(total / 60) % 60
  const h = Math.floor(total / 3600)
  if (h > 0) return `${h}:${pad2(m)}:${pad2(s)}`
  return `${m}:${pad2(s)}`
}
