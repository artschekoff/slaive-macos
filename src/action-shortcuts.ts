// Хоткеи действий главного окна — чистый слой без DOM и React, по тому же
// принципу, что shortcut.ts/menu-state.ts: MainWindow.tsx только вешает
// keydown и вызывает функции отсюда, а решение «какое нажатие какую кнопку
// запускает» тестируется отдельно (action-shortcuts.test.ts).
//
// Это ОКОННЫЕ хоткеи, не глобальные: как Paste/Copy в оверлее, они ловятся
// обычным window keydown и работают только пока окно в фокусе. Через
// tauri-plugin-global-shortcut они не проходят намеренно — глобальная
// регистрация может не удаться, конфликтует с другими приложениями и
// срабатывала бы, когда окна вообще не видно.
import { matchesShortcut, type KeyEventLike } from './shortcut.ts'
import type { ActionShortcutKey, MenuNode } from './action-tree.ts'

/** Ровно те поля настроек, которые нужны разбору нажатия. Отдельный тип, а
 *  не весь Settings: функции ниже не должны уметь читать что-то ещё. */
export type ActionShortcuts = Record<ActionShortcutKey, string>

// Дефолты дублируют Settings::default() на бэкенде (src-tauri/src/settings.rs)
// — та же роль, что у DEFAULT_PASTE_SHORTCUT в shortcut.ts: заглушка до
// первого ответа get_settings, дальше её перекрывают реальные значения.
//
// Почему все шесть с Cmd. Поле текста в главном окне — CodeMirror с Vim.
// В normal-режиме любая голая буква это команда, в insert-режиме голая буква
// это ввод, а Ctrl-комбинации разобраны и там и там (Ctrl-r, Ctrl-o, Ctrl-w,
// Ctrl-v…). Модификатора Cmd в грамматике Vim нет вовсе — поэтому Cmd+буква
// не отбирает у редактирования ничего ни в одном режиме, и обработчик может
// не спрашивать, в фокусе ли редактор. Тот же довод уже записан в Overlay.tsx
// про Cmd+C. Переназначение пользователем требует модификатора (см.
// ShortcutCapture в Settings.tsx) ровно по этой причине.
//
// Буквы — мнемоника действия. Translate получил L («language»), а не T:
// Cmd+T занят глобальным хоткеем записи, и глобальная регистрация съела бы
// его раньше, чем нажатие дошло бы до окна.
// Summarize взял Cmd+U — вторую букву слова: S занят Shorten, а Cmd+M
// (следующая мнемоника) это системный Minimize, который меню приложения
// перехватывает раньше, чем нажатие дойдёт до окна.
export const DEFAULT_ACTION_SHORTCUTS: ActionShortcuts = {
  translateShortcut: 'Super+KeyL',
  askAiShortcut: 'Super+KeyK',
  generateShortcut: 'Super+KeyG',
  fixShortcut: 'Super+KeyF',
  shortenShortcut: 'Super+KeyS',
  summarizeShortcut: 'Super+KeyU',
}

/** Хоткей Accept — «предложение ИИ становится текстом окончательно».
 *  Не поле ActionShortcuts: тот тип описывает ровно узлы дерева действий
 *  (ActionShortcutKey), а Accept не пункт меню — он закрывает цикл
 *  применения (см. apply-state.ts). Дефолт дублирует Settings::default()
 *  на бэкенде, как и DEFAULT_ACTION_SHORTCUTS выше.
 *
 *  Shift+Cmd+Enter — тот же «подтвердить», что у Paste (Cmd+Enter), но с
 *  добавленным Shift, и это не педантизм. Accept ЗАМЕНЯЕТ текст пользователя
 *  предложением модели, а прежний после этого достаётся только через Undo
 *  редактора; при этом Cmd+Enter в том же окне жмут привычно и часто.
 *  Соседство помогает помнить (⇧⌘⏎ принять → ⌘⏎ вставить), лишний Shift
 *  мешает попасть случайно. */
export const DEFAULT_ACCEPT_SHORTCUT = 'Shift+Super+Enter'

/** Escape — единственная комбинация приложения, которая НЕ настраивается, и
 *  единственная, за которой закреплены сразу два действия главного окна:
 *  Back (уровень меню выше) и Cancel (выход из цикла применения).
 *
 *  Почему не настраивается. Escape в этом окне разбирается литерально и
 *  послойно: закрыть модальный слой права → отдать insert-режиму vim выход в
 *  normal → закрыть историю → Cancel → Back (см. обработчик в MainWindow.tsx).
 *  Три верхних слоя обязаны остаться на Escape при любых настройках — это
 *  системное «выйти отсюда», а выход из insert-режима вообще принадлежит
 *  редактору. Сделать настраиваемыми только два нижних значило бы завести
 *  ВТОРОЙ источник правды о том, что делает эта клавиша, и разъехаться они
 *  могли бы молча.
 *
 *  Столкнуться с назначенной комбинацией Escape не может структурно, а не по
 *  договорённости: ShortcutCapture трактует нажатие Escape как отмену записи
 *  комбинации, поэтому ни в одно поле настроек он не попадает. Поэтому его и
 *  нет в SHORTCUT_FIELDS — там перечислены ХРАНИМЫЕ поля.
 *
 *  Значение в формате акселератора, чтобы бейдж рисовался тем же
 *  formatShortcutBadge, что и у остальных кнопок ("Escape" -> "⎋"), а не
 *  зашитым символом. */
export const ESCAPE_SHORTCUT = 'Escape'

/** Сколько пунктов подменю получают позиционный хоткей. Больше девяти в
 *  одном уровне не бывает у клавиатурного ряда цифр; десятому кнопка
 *  остаётся без бейджа, а не получает нечитаемую комбинацию. */
const MAX_POSITIONAL = 9

/**
 * Акселератор кнопки узла на ТЕКУЩЕМ уровне меню.
 *
 * Корневой уровень — настраиваемый хоткей действия из настроек.
 * Подуровень (языки под Translate) — позиционный Cmd+1…Cmd+9, не настройка:
 * пункты подменю приходят из данных дерева и могут меняться составом, а
 * хранимая настройка на каждый язык означала бы миграцию файла настроек и
 * новую строку в окне настроек на каждый добавленный язык. Позиция ничего не
 * хранит и остаётся верной при любой правке дерева. Cmd взят и здесь по той
 * же причине, что у корневых: голая цифра — это ввод в insert-режиме Vim.
 *
 * `null` — у кнопки хоткея нет (узел без `shortcutKey`, либо десятый и
 * дальше пункт подменю).
 */
export function shortcutFor(
  node: MenuNode,
  index: number,
  atRoot: boolean,
  shortcuts: ActionShortcuts
): string | null {
  if (atRoot) return node.shortcutKey ? shortcuts[node.shortcutKey] : null
  return index < MAX_POSITIONAL ? `Super+Digit${index + 1}` : null
}

/**
 * Акселератор пункта быстрого вызова (список недавних действий в корне меню).
 *
 * Позиционный ⌘1…⌘3, тот же механизм и та же запись, что у пунктов подменю:
 * состав списка меняется на каждое выполненное действие, и хранимая настройка
 * на каждый слот означала бы поле настроек, которое указывает на разное в
 * разные дни. Позиция ничего не хранит — значит, и в SHORTCUT_FIELDS
 * (shortcut-conflicts.ts) добавлять нечего: там перечислены ХРАНИМЫЕ поля.
 *
 * ПОЧЕМУ СТОЛКНОВЕНИЯ НЕ ПРОИСХОДИТ. ⌘1…⌘9 заняты пунктами подменю, но
 * подменю и корень — разные уровни, и на экране всегда один: `nodeForKey`
 * разбирает ровно тот уровень, который нарисован. А вот настраиваемую
 * комбинацию действия пользователь МОЖЕТ назначить на ⌘1 — и тогда в корне
 * одна клавиша означала бы две кнопки, то есть одна из них молча перестала бы
 * срабатывать: ровно та беда, ради которой написан shortcut-conflicts.ts.
 * Поэтому проверяем, а не принимаем на веру: занятый номер быстрый пункт НЕ
 * получает. Он остаётся без бейджа (и доступен стрелками и мышью), а
 * настроенная комбинация продолжает делать то, что написано в настройках.
 * Молчания при этом нет: бейдж — и есть обещание, и там, где его нет,
 * ничего не обещано.
 *
 * `taken` — все комбинации, которые уже перехватывает главное окно (хоткеи
 * действий, Paste, Copy, Accept). Передаёт вызывающая сторона: этот файл не
 * должен уметь читать настройки, он умеет только сопоставлять нажатия.
 */
export function quickShortcutFor(index: number, taken: readonly string[]): string | null {
  if (index < 0 || index >= MAX_POSITIONAL) return null
  const accel = `Super+Digit${index + 1}`
  return taken.includes(accel) ? null : accel
}

/** Какой пункт быстрого вызова запускает это нажатие. `null` — ни один.
 *  `count` — сколько пунктов сейчас на экране: хоткей пункта, которого в
 *  списке нет, не срабатывает по построению, как и у остальных кнопок. */
export function quickIndexForKey(
  e: KeyEventLike,
  count: number,
  taken: readonly string[]
): number | null {
  for (let i = 0; i < count; i++) {
    const accel = quickShortcutFor(i, taken)
    if (accel && matchesShortcut(e, accel)) return i
  }
  return null
}

/**
 * Какой узел текущего уровня запускает это нажатие. `null` — ни один.
 *
 * Берёт ровно тот уровень, который сейчас нарисован кнопками, поэтому хоткей
 * недоступной кнопки не сработает по построению, а не по отдельной проверке:
 * кнопки нет на экране — узла нет и в `level`. Остальные условия
 * недоступности (пустой текст, запрос в полёте, открытая панель
 * Accept/Cancel, форма Ask AI) — состояние окна, их проверяет MainWindow.tsx
 * перед вызовом.
 */
export function nodeForKey(
  e: KeyEventLike,
  level: readonly MenuNode[],
  atRoot: boolean,
  shortcuts: ActionShortcuts
): MenuNode | null {
  for (let i = 0; i < level.length; i++) {
    const accel = shortcutFor(level[i], i, atRoot, shortcuts)
    if (accel && matchesShortcut(e, accel)) return level[i]
  }
  return null
}
