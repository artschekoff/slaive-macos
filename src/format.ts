// Форматирование чисел для интерфейса настроек. Чистое, без DOM — чтобы
// «1.6 GB» рядом с кнопкой Delete проверялось тестом, а не на глаз.

/**
 * Размер файла человеческими единицами. Десятичные приставки (1 ГБ = 1000 МБ),
 * а не двоичные: так же считают и Finder, и страница модели на huggingface,
 * и расхождение в 7% между «1.5 GiB» и «1.6 GB» выглядело бы как ошибка.
 *
 * Один знак после запятой у гигабайтов и ноль у мегабайтов — 1.6 GB несёт
 * смысл, а 488.3 MB нет.
 */
export function formatBytes(bytes: number): string {
  if (!Number.isFinite(bytes) || bytes <= 0) return '0 MB'
  if (bytes >= 1_000_000_000) return `${(bytes / 1_000_000_000).toFixed(1)} GB`
  if (bytes >= 1_000_000) return `${Math.round(bytes / 1_000_000)} MB`
  // Меньше мегабайта — модель VAD весит 0.9 МБ, и «0 MB» про неё было бы
  // враньём, а «885098 bytes» — шумом.
  return `${(bytes / 1_000_000).toFixed(1)} MB`
}
