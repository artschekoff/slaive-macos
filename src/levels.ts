// Масштабирование дорожки уровня. Живёт отдельным модулем, а не внутри
// Overlay.tsx, по той же причине, что и transcript-editor.ts: чистая функция
// должна поддаваться тесту без React и DOM (`npm test` гоняет node --test
// прямо по .ts).
//
// ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. Пока запись идёт, столбики набегают слева направо —
// сколько успели, столько и нарисовано, итоговая длительность ещё неизвестна.
// Как только запись остановлена, дорожка перестаёт быть живым индикатором и
// становится статичной формой волны ВСЕЙ записи. А головка воспроизведения и
// перемотка считают позицию как долю длительности от полной ширины дорожки.
// Пока рисунок занимал левую треть, а головка ходила по всей ширине, это были
// два разных масштаба: позиция в звуке не совпадала с тем, что нарисовано.
// `resampleLevels` приводит рисунок к масштабу «вся ширина = вся запись», в
// котором живёт головка.
//
// ЧЕСТНОСТЬ ДОРОЖКИ ПРИ ЭТОМ НЕ СТРАДАЕТ, и это главное ограничение здесь:
// дорожка — диагностический прибор, отличающий тишину от мёртвого микрофона
// (macOS при отказе в доступе отдаёт поток нулей, а не ошибку). Раскладка по
// ширине — ПЕРЕРАЗБИЕНИЕ уже измеренных значений, а не их подделка:
//   - при растяжении (замеров меньше, чем столбиков) значение повторяется —
//     это ближайший сосед, а не интерполяция, которая могла бы поднять
//     соседей нуля выше нуля;
//   - при сжатии (замеров больше, чем столбиков) берётся максимум по окну —
//     ровно то же, что делает бэкенд, складывая пики чанков в один кадр;
//   - никакой минимальной высоты не подмешивается.
// Следствие: массив из одних нулей на выходе остаётся массивом из одних
// нулей при любом масштабе. Тишина остаётся тишиной, мёртвый микрофон —
// пустой дорожкой.

/** Раскладывает замеры уровня ровно на `cap` столбиков.
 *
 *  `cap` — сколько столбиков помещается по ширине контейнера (см.
 *  BAR_FOOTPRINT_PX в Overlay.tsx), то есть «вся ширина дорожки». */
export function resampleLevels(levels: number[], cap: number): number[] {
  if (cap <= 0 || levels.length === 0) return []
  if (levels.length === cap) return levels
  const n = levels.length
  const out: number[] = new Array(cap)
  for (let i = 0; i < cap; i++) {
    const start = Math.floor((i * n) / cap)
    // Окно минимум в один замер: при растяжении начало и конец совпадают, и
    // столбик просто повторяет ближайший замер.
    const end = Math.max(start + 1, Math.floor(((i + 1) * n) / cap))
    let max = 0
    for (let j = start; j < end && j < n; j++) {
      if (levels[j] > max) max = levels[j]
    }
    out[i] = max
  }
  return out
}
