// Smart Replace — пары «фраза → подстановка», отдельно от панели по тому же
// принципу, что dictor-roles.ts: замену можно проверить тестом, разметку —
// нельзя. Применяется к готовой расшифровке ДО показа и до ИИ-правки
// (см. Overlay.tsx): модель правит уже подставленный текст, и роль не
// успевает «исправить» ссылку или имя, ради которых пара и заведена.

/** Зеркало `SmartReplace` из settings.rs (serde camelCase). */
export type SmartReplace = {
  /** UUID, выдаётся при создании пары (crypto.randomUUID), как у ролей. */
  id: string
  from: string
  to: string
}

const escapeRegExp = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/** Заменяет каждую произнесённую фразу её подстановкой.
 *
 *  Правила выбраны по тому, как фразы диктуют, а не печатают:
 *  - без учёта регистра — whisper сам решает, где поставить заглавную;
 *  - только целая фраза по границам слов — «кот» не должен срабатывать
 *    внутри «который». Границы через \p{L}\p{N}, а не \b: \b знает только
 *    ASCII и на кириллице не работает;
 *  - пары применяются по порядку списка; результат одной замены виден
 *    следующей — это даёт цепочки, и порядок в настройках осмыслен. */
export function applySmartReplaces(text: string, pairs: SmartReplace[]): string {
  let out = text
  for (const p of pairs) {
    const from = p.from.trim()
    if (!from) continue
    const re = new RegExp(
      `(?<![\\p{L}\\p{N}])${escapeRegExp(from)}(?![\\p{L}\\p{N}])`,
      'giu',
    )
    // Замена функцией, не строкой: в p.to пользователь пишет буквальный
    // текст, и "$&" в нём — текст, а не спецсинтаксис String.replace.
    out = out.replace(re, () => p.to)
  }
  return out
}
