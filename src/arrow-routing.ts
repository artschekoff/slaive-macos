// Кому сейчас достаются стрелки/Home/End — списку (столбец действий или
// сетка истории, см. отчёт) или редактору. Один и тот же механизм для ОБОИХ
// списков окна: решает не то, куда сейчас указывает DOM-фокус, а РЕЖИМ Vim —
// именно фокус и был причиной бага (окно кладёт фокус в редактор на каждый
// новый текст, и без этого правила стрелки не доходили до списка, пока
// пользователь не нажмёт Tab вручную).
//
// Правило РАЗРЕШИТЕЛЬНОЕ (пускает список только в 'normal'), а не
// запретительное ("всё, кроме insert") — и это не одно и то же. Пакет
// сообщает четыре режима: 'normal' / 'insert' / 'visual' / 'replace' (см.
// отчёт, проверено по исходнику @replit/codemirror-vim-core/vim.js — ровно
// столько разных строк уходит в сигнал `vim-mode-change`). В VISUAL стрелки
// расширяют выделение — то же движение, что и hjkl в этом режиме, которым
// visual только и пользуется; в REPLACE они двигают курсор внутри
// перезаписи. Оба этих режима — про правку/выделение текста, ровно как
// insert, а не про навигацию по списку. Разрешительный список короче
// запретительного и не сломается молча, если пакет когда-нибудь добавит
// пятый режим: неизвестное имя останется у редактора, а не случайно
// перехватится списком.
export function arrowsControlList(vimMode: string, hasPendingOperator: boolean): boolean {
  // hasPendingOperator — единственная поправка к "просто NORMAL": оператор
  // vim (`d`/`c`/`y`/`>`...) ждёт МОУШЕН, а не завершён, и в этот момент
  // vim-mode-change не сообщает отдельного режима — mode остаётся 'normal'
  // (см. hasPendingVimOperator в transcript-editor.ts). Стрелка в этот
  // момент — аргумент оператора ("удалить до..."), а не навигация по
  // списку; без этой поправки список перехватывал бы клавишу, а vim
  // оставался бы с незавершённой командой, которую больше нечем закрыть.
  return vimMode === 'normal' && !hasPendingOperator
}
