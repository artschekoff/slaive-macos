// Бюджет подсказки whisper для словаря терминов.
//
// Зачем это вообще существует отдельным модулем. whisper.cpp берёт из
// initial_prompt не больше `n_text_ctx/2` токенов, а `n_text_ctx` у всех
// моделей 448 — потолок 224 токена. Лишнее отбрасывается С НАЧАЛА списка и
// МОЛЧА: длинный словарь не расширяет охват, а тихо теряет первые термины.
// Ни ошибки, ни лога, ни отличия в поведении — кроме того, что слова, ради
// которых словарь и заводили, перестают подсказываться.
//
// Сид проверен тестом на стороне Rust (settings.rs:
// default_dictionary_fits_whisper_prompt_budget), но тест защищает только
// ДЕФОЛТ. Пользователь, дописывающий свои термины, до появления этого счётчика
// не имел вообще никакого способа заметить, что перешагнул потолок.
//
// Второй источник правды рядом с Rust — осознанно, ровно как MIN_GAIN и
// MIN_VAD_THRESHOLD в Settings.tsx: расхождение не ломает приложение (whisper
// всё равно обрежет сам), но числа держим равными явно.

/** Потолок токенов подсказки: `n_text_ctx/2`, n_text_ctx = 448 у всех
 *  моделей whisper. Совпадает с MAX_PROMPT_TOKENS в тесте settings.rs. */
export const MAX_PROMPT_TOKENS = 224

/** Символов на токен при оценке. Английский текст у BPE whisper — порядка
 *  четырёх символов на токен; берём 3.5, то есть ошибаемся в сторону
 *  «занято больше, чем на самом деле». Та же константа и то же направление
 *  запаса, что в тесте settings.rs: счётчик, который успокаивает раньше
 *  времени, хуже бесполезного. */
const CHARS_PER_TOKEN = 3.5

/** Собирает подсказку из словаря ровно так же, как `whisper::initial_prompt`
 *  на бэкенде: строки И запятые — разделители, пустые куски выбрасываются,
 *  остальное склеивается через ", ". Оценивать нужно именно результат
 *  склейки, а не исходный текст поля: одна и та же пара терминов занимает
 *  разное число символов, написанная через перенос строки ("a\nb") и через
 *  запятую ("a, b"), — а до whisper в обоих случаях доезжает "a, b".
 *
 *  NUL вырезается для полного совпадения с бэкендом (там это защита от
 *  правки settings.json руками — CString паникует на нуле внутри строки). */
export function promptFromDictionary(dictionary: string): string {
  return dictionary
    .split(/[\n,]/)
    // .replace(/\0/g) вместо .replaceAll — цель компиляции проекта ниже
    // ES2021, где .replaceAll ещё нет (см. tsconfig).
    .map((term) => term.replace(/\0/g, '').trim())
    .filter((term) => term.length > 0)
    .join(', ')
}

/** Консервативная оценка длины подсказки в токенах. Токенизатора whisper во
 *  фронтенде нет и тащить его сюда ради счётчика незачем — считаем по
 *  символам, как и Rust-тест сида. */
export function estimatePromptTokens(dictionary: string): number {
  return Math.ceil(promptFromDictionary(dictionary).length / CHARS_PER_TOKEN)
}
